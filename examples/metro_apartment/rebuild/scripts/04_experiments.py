def z(p):
    """标准正态分位数（Acklam 有理逼近，足够本用途）"""
    if p <= 0 or p >= 1: raise ValueError
    a=[-3.969683028665376e+01,2.209460984245205e+02,-2.759285104469687e+02,
       1.383577518672690e+02,-3.066479806614716e+01,2.506628277459239e+00]
    b=[-5.447609879822406e+01,1.615858368580409e+02,-1.556989798598866e+02,
       6.680131188771972e+01,-1.328068155288572e+01]
    c=[-7.784894002430293e-03,-3.223964580411365e-01,-2.400758277161838e+00,
       -2.549732539343734e+00,4.374664141464968e+00,2.938163982698783e+00]
    d=[7.784695709041462e-03,3.224671290700398e-01,2.445134137142996e+00,3.754408661907416e+00]
    pl=0.02425
    if p < pl:
        q=math.sqrt(-2*math.log(p))
        return (((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5])/((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1)
    if p > 1-pl:
        q=math.sqrt(-2*math.log(1-p))
        return -(((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5])/((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1)
    q=p-0.5; r=q*q
    return (((((a[0]*r+a[1])*r+a[2])*r+a[3])*r+a[4])*r+a[5])*q/(((((b[0]*r+b[1])*r+b[2])*r+b[3])*r+b[4])*r+1)

def n_per_arm(p1, mde_abs, alpha=0.05, power=0.80, k=1.0):
    """每臂所需样本量（双侧两比例检验，等方差/不等样本通用式）
       n1 = ( z_{1-a/2}*sqrt((1+1/k)*pbar*(1-pbar)) + z_{power}*sqrt(p1(1-p1)+p2(1-p2)/k) )^2 / d^2
       k = n2/n1。此处只做等样本设计(k=1)，保留参数以便复核。"""
    p2 = p1 + mde_abs
    if not (0 < p1 < 1) or not (0 < p2 < 1) or mde_abs <= 0: return float('inf')
    pbar = (p1 + k*p2)/(1+k)
    num = (z(1-alpha/2)*math.sqrt((1+1/k)*pbar*(1-pbar))
           + z(power)*math.sqrt(p1*(1-p1) + p2*(1-p2)/k))**2
    return num/(mde_abs**2)

def mde(n, p1, alpha=0.05, power=0.80):
    """给定每臂样本量，反解可检测的最小绝对效应。
    单调性：Δ 越大 → 所需 n 越小。故 n_per_arm(p1,Δ) 关于 Δ 单调递减。
    我们要找 Δ* 使 n_per_arm(p1,Δ*) = n。
      若 n_per_arm(p1, 极小Δ) ≤ n → 该样本量对任何 Δ 都够，MDE→0（返回 0 并标注）
      若 n_per_arm(p1, 极大Δ) >  n → 该样本量连最大可能效应都测不出（返回 inf）"""
    lo_d, hi_d = 1e-6, min(0.999 - p1, 0.95)
    if n_per_arm(p1, lo_d, alpha, power) <= n: return 0.0
    if n_per_arm(p1, hi_d, alpha, power) >  n: return float('inf')
    lo, hi = lo_d, hi_d
    for _ in range(200):
        mid=(lo+hi)/2
        if n_per_arm(p1, mid, alpha, power) > n: lo=mid
        else: hi=mid
    return (lo+hi)/2

