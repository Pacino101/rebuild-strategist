def validate_exp(e, errors):
    req = ["experiment_id","hypothesis","audience","variant","primary_metric","guardrails","decision_rule","status"]
    allowed = set(req + ["control","minimum_detectable_effect","sample_logic","duration",
                          "analysis_plan","result","limitations"])
    eid = e.get("experiment_id","?")
    for k in req:
        if k not in e or not e[k]: errors.append(f"{eid}: 缺必填字段 {k}")
    extra = set(e) - allowed
    if extra: errors.append(f"{eid}: schema 未允许字段 {extra}")
    if e.get("status") not in {"proposed","approved","running","complete","stopped","rejected"}:
        errors.append(f"{eid}: status 非法")
    if not isinstance(e.get("guardrails"), list): errors.append(f"{eid}: guardrails 必须是数组")
    if e.get("status") in {"running","complete"} and "control" not in e:
        errors.append(f"{eid}: 做出因果声称的实验必须有 control")
    for k in ("decision_rule",):
        v = e.get(k,"")
        for kw in ("通过","失败","不确定"):
            if kw not in v: errors.append(f"{eid}: decision_rule 未覆盖『{kw}』分支（技能要求预置三态）")
    return errors

