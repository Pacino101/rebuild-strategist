def validate(node, path="root", errors=None):
    if errors is None: errors = []
    req = ["metric_name","metric_type","definition","unit","period","source_of_truth","owner"]
    allowed = set(req + ["formula","cohort","baseline","target","guardrail_threshold","limitations","children"])
    types = {"outcome","driver","diagnostic","activity","guardrail"}
    for k in req:
        if k not in node or not node[k]:
            errors.append(f"{path}: 缺必填字段 {k}")
    extra = set(node) - allowed
    if extra: errors.append(f"{path}: 出现 schema 未允许字段 {extra}（additionalProperties=false 会直接拒绝）")
    if node.get("metric_type") not in types:
        errors.append(f"{path}: metric_type={node.get('metric_type')!r} 不在枚举内")
    if "children" in node:
        if not isinstance(node["children"], list):
            errors.append(f"{path}: children 必须是数组")
        else:
            for i, c in enumerate(node["children"]):
                validate(c, f"{path} > {c.get('metric_name','?')}", errors)
    return errors

def validate_tree(tree):
    """顶层对象有独立 schema（tree_id/objective/instrumentation/attribution_assumption/nodes），
    与 node 的 $defs 不同 —— 必须分开校验，否则 additionalProperties=false 会误报。"""
    e = []
    allowed_top = {"tree_id","objective","instrumentation","attribution_assumption","root","nodes"}
    extra = set(tree) - allowed_top
    if extra: e.append(f"tree: schema 未允许的顶层字段 {extra}")
    if "root" not in tree and "nodes" not in tree:
        e.append("tree: anyOf(root, nodes) 未满足")
    if not isinstance(tree.get("instrumentation"), list):
        e.append("tree: instrumentation 必须是数组")
    if not isinstance(tree.get("nodes", []), list):
        e.append("tree: nodes 必须是数组")
    for n in tree.get("nodes", []):
        validate(n, f"nodes[{n.get('metric_name','?')}]", e)
    return e

errs = validate_tree(KPI_TREE)
