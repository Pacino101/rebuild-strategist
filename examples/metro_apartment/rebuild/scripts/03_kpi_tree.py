import json, re, sys

NODES = []

def N(name, mtype, definition, unit, period, sot, owner, formula=None, baseline=None,
      target=None, guardrail=None, limitations=None, children=None, cohort=None):
    n = dict(metric_name=name, metric_type=mtype, definition=definition, unit=unit,
             period=period, source_of_truth=sot, owner=owner)
    if formula: n["formula"] = formula
    if baseline: n["baseline"] = baseline
    if target: n["target"] = target
    if guardrail: n["guardrail_threshold"] = guardrail
    if limitations: n["limitations"] = limitations
    if cohort: n["cohort"] = cohort
    if children: n["children"] = children
    return n

